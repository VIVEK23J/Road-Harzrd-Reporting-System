function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    // Register Service Worker for PWA capability
    if (typeof window !== "undefined" && "serviceWorker" in navigator) {
      navigator.serviceWorker.register("/sw.js").catch((err) => {
        console.warn("[PWA] Service worker registration error:", err);
      });
    }

    // Handle Auth state changes across components
    const handleAuthChange = () => {
      router.invalidate();
      queryClient.invalidateQueries();
    };

    window.addEventListener("roadwatch_auth_change", handleAuthChange);
    return () => {
      window.removeEventListener("roadwatch_auth_change", handleAuthChange);
    };
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <AppShell>
        <Outlet />
      </AppShell>
      <Toaster position="top-center" richColors />
    </QueryClientProvider>
  );
}
